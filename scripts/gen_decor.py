products = json.load(open(PJ))
products = [p for p in products if p['cat'] != 'dekor']  # идемпотентно
sku = 3100000
subs, packs_js = [], []
for pk in PACKS:
    slots_js = []
    for si, (sub, title, base, unit, emoji, spec, variants) in enumerate(pk['slots']):
        if sub not in subs:
            subs.append(sub)
        ids = []
        for vi, (style, color, material) in enumerate(variants):
            price = base if vi < 3 else premium(base, 1.15 if vi == 3 else 1.3)
            pid = f"dekor-{pk['id']}-{si + 1}-{vi + 1}"
            sku += 1
            products.append({
                'id': pid, 'cat': 'dekor', 'sub': sub,
                'name': (lambda main, rest: f'{main} «{style}», {color}' + (f', {rest}' if rest else ''))(*(title.split(', ', 1) + [''])[:2]),
                'brand': 'ОМА Home' if vi < 3 else 'ОМА Home Premium',
                'price': price, 'unit': unit,
                'rating': [5, 4, 5, 5, 4][(si + vi) % 5], 'reviews': 3 + (si * 7 + vi * 5) % 40,
                'emoji': emoji, 'sku': str(sku), 'stock': 12 + (si * 11 + vi * 7) % 60,
                'desc': f'{title} из коллекции «{style}». {pk["room"]}: позиция пакета декора «{pk["name"]}». Материал — {material}.',
                'specs': [{'name': 'Цвет', 'value': color}, {'name': 'Материал', 'value': material},
                          {'name': spec[0], 'value': spec[1]}],
                'popular': False,
            })
            ids.append(pid)
        slots_js.append({'id': f"{pk['id']}-{si + 1}", 'title': title.split(',')[0], 'variants': ids})
    packs_js.append({'id': pk['id'], 'name': pk['name'], 'room': pk['room'], 'emoji': pk['emoji'],
                     'from': pk['from_'], 'to': pk['to'], 'desc': pk['desc'], 'slots': slots_js})

# Дописываем новые товары в конец файла, не трогая форматирование существующих
new = [x for x in products if x['cat'] == 'dekor']
raw = open(PJ).read()
if '"cat": "dekor"' in raw:
    raise SystemExit('декор уже в products.json — сначала откатите файл')
body = raw.rstrip().rstrip(']').rstrip()
def fmt(x):
    specs = ',\n'.join('      ' + json.dumps(s, ensure_ascii=False).replace('{', '{ ').replace('}', ' }') for s in x['specs'])
    head = json.dumps({k: v for k, v in x.items() if k not in ('specs', 'popular')}, ensure_ascii=False, indent=2)
    head = '\n'.join('  ' + l for l in head.rstrip('}').rstrip().splitlines())
    return head + ',\n    "specs": [\n' + specs + '\n    ],\n    "popular": false\n  }'
open(PJ, 'w').write(body + ',\n' + ',\n'.join(fmt(x) for x in new) + '\n]\n')

