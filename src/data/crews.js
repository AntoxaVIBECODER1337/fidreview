/** Быстрый поиск: по названию бригады или по специализациям */
export const crewMatchesQuery = (c, query) => {
  const q = (query ?? '').trim().toLowerCase()
  if (!q) return true
  return (
    c.name.toLowerCase().includes(q) ||
    c.specialties.some((s) => specialtyLabel(s).toLowerCase().includes(q))
  )
}

