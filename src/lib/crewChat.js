import { startLabel } from '../data/crews'

/**
 * Демо-ответы бригады в чате «до связи».
 * Отвечаем по смыслу вопроса: цена, сроки, материалы, замер, гарантия.
 */
const RULES = [
  {
    keys: ['цен', 'стоим', 'сколько', 'смет', 'дорого', 'руб'],
    reply: (c) =>
      `Наша ставка — ${c.rate} р. за м². Точную смету зафиксируем на бесплатном замере, после него цена не меняется.`,
  },
  {
    keys: ['когда', 'срок', 'начать', 'старт', 'свобод', 'завтра'],
    reply: (c) => `Можем выйти на объект: ${startLabel(c.startDays)}. Скажите удобный день для замера?`,
  },
  {
    keys: ['материал', 'закуп', 'привез', 'доставк', 'товар'],
    reply: () =>
      'Работаем с материалами ОМА: соберём список в проекте, доставка с подъёмом прямо на объект. Можно и ваши материалы.',
  },
  {
    keys: ['замер', 'приех', 'посмотр', 'выезд'],
    reply: () => 'Выезд на замер бесплатный. Оставьте адрес — подтвердим время в течение часа.',
  },
  {
    keys: ['гарант', 'договор', 'оплат'],
    reply: (c) =>
      `Гарантия ${c.guarantee} ${c.guarantee === 1 ? 'год' : 'года'}, работаем по договору. Оплата через ОМА — после приёмки каждого этапа.`,
  },
]

export const QUICK_QUESTIONS = [
  'Сколько будет стоить?',
  'Когда сможете начать?',
  'Работаете с материалами ОМА?',
  'Можно бесплатный замер?',
]

export function crewReply(crew, text) {
  const t = text.toLowerCase()
  const rule = RULES.find((r) => r.keys.some((k) => t.includes(k)))
  if (rule) return rule.reply(crew)
  return `Здравствуйте! Это ${crew.name}. Опишите, что нужно сделать и примерную площадь — сориентируем по цене и срокам.`
}

export const greeting = (crew) =>
  crew.isOma
    ? 'Здравствуйте! Бригада ОМА Сервис на связи. Чем можем помочь с ремонтом?'
    : `Здравствуйте! ${crew.name} на связи. Спрашивайте — ответим до оформления проекта.`
